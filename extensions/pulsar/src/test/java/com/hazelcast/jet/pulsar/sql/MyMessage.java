package com.hazelcast.jet.pulsar.sql;

import java.io.Serial;
import java.io.Serializable;
import java.util.Objects;

@SuppressWarnings("unused")
public final class MyMessage implements Serializable {
    @Serial
    private static final long serialVersionUID = 1L;

    String title;
    String content;

    public MyMessage() {
    }

    public MyMessage(String title, String content) {
        this.title = title;
        this.content = content;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getContent() {
        return content;
    }

    public void setContent(String content) {
        this.content = content;
    }

    @Override
    public boolean equals(Object obj) {
        if (obj == this) {
            return true;
        }
        if (obj == null || obj.getClass() != this.getClass()) {
            return false;
        }
        var that = (MyMessage) obj;
        return Objects.equals(this.title, that.title) && Objects.equals(this.content, that.content);
    }

    @Override
    public int hashCode() {
        return Objects.hash(title, content);
    }

    @Override
    public String toString() {
        return "MyMessage[" + "title=" + title + ", " + "content=" + content + ']';
    }

}
